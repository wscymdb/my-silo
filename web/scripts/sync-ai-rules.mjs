import { mkdir, readFile, readdir, unlink, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../', import.meta.url));
const sourceDir = join(root, 'ai/rules');
const generatedHeader = '<!-- Generated by web/scripts/sync-ai-rules.mjs from ai/rules/. Do not edit. -->';
const legacyHeader = '<!-- Generated by scripts/sync-ai-rules.mjs from ai/rules/. Do not edit. -->';
const isGenerated = content => content?.startsWith(generatedHeader) || content?.startsWith(legacyHeader);
const startMarker = '<!-- BEGIN GENERATED AI RULES -->';
const endMarker = '<!-- END GENERATED AI RULES -->';
const targets = process.argv.slice(2);
const selected = targets.length ? [...new Set(targets)] : ['antigravity', 'codex'];

async function readOptional(path) {
  try {
    return await readFile(path, 'utf8');
  } catch (error) {
    if (error.code === 'ENOENT') return null;
    throw error;
  }
}

async function writeChanged(path, content) {
  if (await readOptional(path) === content) return;
  await mkdir(dirname(path), { recursive: true });
  await writeFile(path, content);
}

async function syncAntigravity(rules) {
  const destination = join(root, '.agents/rules');
  await mkdir(destination, { recursive: true });
  // Validate before overwriting: accept the original rule during first migration.
  for (const rule of rules) {
    const existing = await readOptional(join(destination, rule.name));
    if (existing !== null && !isGenerated(existing) && existing.trim() !== rule.content.trim()) {
      throw new Error(`Refusing to overwrite handwritten rule: .agents/rules/${rule.name}`);
    }
  }
  for (const rule of rules) {
    await writeChanged(join(destination, rule.name), `${generatedHeader}\n\n${rule.content.trim()}\n`);
  }
  const names = new Set(rules.map(rule => rule.name));
  for (const entry of await readdir(destination, { withFileTypes: true })) {
    if (!entry.isFile() || !entry.name.endsWith('.md') || names.has(entry.name)) continue;
    const path = join(destination, entry.name);
    if (isGenerated(await readOptional(path))) await unlink(path);
  }
}

async function syncCodex(rules) {
  const path = join(root, 'AGENTS.md');
  const existing = await readOptional(path) ?? '';
  const start = existing.indexOf(startMarker);
  const end = existing.indexOf(endMarker);
  if ((start === -1) !== (end === -1) || (start !== -1 && end < start)
      || existing.indexOf(startMarker, start + startMarker.length) !== -1
      || existing.indexOf(endMarker, end + endMarker.length) !== -1) {
    throw new Error('AGENTS.md has invalid or duplicate generated markers; refusing to overwrite.');
  }
  const body = rules.map(rule => `<!-- Source: ai/rules/${rule.name} -->\n\n${rule.content.trim()}`).join('\n\n');
  const block = `${startMarker}\n${generatedHeader}\n\n${body}\n${endMarker}`;
  const result = start === -1
    ? `${existing}${existing && !existing.endsWith('\n') ? '\n' : ''}${existing ? '\n' : ''}${block}\n`
    : existing.slice(0, start) + block + existing.slice(end + endMarker.length);
  await writeChanged(path, result);
}

try {
  for (const target of selected) {
    if (!['antigravity', 'codex'].includes(target)) throw new Error(`Unknown target: ${target}. Use antigravity or codex.`);
  }
  const entries = await readdir(sourceDir, { withFileTypes: true });
  const names = entries.filter(entry => entry.isFile() && entry.name.endsWith('.md')).map(entry => entry.name).sort();
  const rules = await Promise.all(names.map(async name => ({ name, content: await readFile(join(sourceDir, name), 'utf8') })));
  for (const target of selected) {
    await (target === 'codex' ? syncCodex(rules) : syncAntigravity(rules));
    console.log(`Generated ${target} rules from ${rules.length} source file(s).`);
  }
} catch (error) {
  console.error(error.message);
  process.exitCode = 1;
}
